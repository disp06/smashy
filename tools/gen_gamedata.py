# Generates src/gamedata.h from meta.json (model indices, footprints, colliders, tile table)
import json, struct, numpy as np, math
import os as _os
APK = _os.environ.get('SMASHY_APK_DIR', 'work/apk') + '/'
WORK = _os.environ.get('SMASHY_WORK', 'work') + '/'

B = WORK
meta = json.load(open(B + 'meta.json'))
M = meta['models']
out = []
w = out.append
w('// generated by gen_gamedata.py - do not edit')
w('#pragma once')

# texture biome mapping: find model texture ids equal in content to texNormal[k]
d = open(B + 'data/textures.pak', 'rb').read()
n = struct.unpack_from('<I', d, 4)[0]
blobs = []
for i in range(n):
    off, ln = struct.unpack_from('<II', d, 8 + 8 * i)
    blobs.append(d[off:off + ln])
g = meta['groundtex']
def texarr(i):
    b = blobs[i]; W, H, f = struct.unpack_from('<III', b, 4)
    pal = np.frombuffer(b, np.uint8, 1024, 16).reshape(256, 4); idx = np.frombuffer(b, np.uint8, W * H, 16 + 1024).reshape(H, W)
    return pal[idx].astype(np.int32)
md = open(B + 'data/models.pak', 'rb').read()
def texids(i):
    off, ln = struct.unpack_from('<II', md, 8 + 8 * i); b = md[off:off + ln]; ns, nc = struct.unpack_from('<ii', b, 28); o = 36 + nc * 28; r = set()
    for s_ in range(ns):
        t, dd, nv = struct.unpack_from('<iii', b, o); o += 12 + nv * 20; r.add(t)
    return r
used = set()
for nm in meta['tiles']:
    if nm.startswith('road'): used |= texids(M['tile_' + nm]['idx'])
swap = []
for tid in sorted(used):
    A = texarr(tid); best = None
    for k in range(4):
        Bn = texarr(g['texNormal'][k])
        if Bn.shape != A.shape: continue
        dd = np.abs(A - Bn).mean()
        if best is None or dd < best[0]: best = (dd, k)
    if best and best[0] < 20:
        k = best[1]; swap.append((tid, g['texNormal'][k], g['texDessert'][k], g['texGrass'][k]))
w('#define NUM_TEXSWAP %d' % len(swap))
w('static const short TEXSWAP[][4] = {%s};' % ','.join('{%d,%d,%d,%d}' % s for s in swap))

# ground colours per biome: sample sidewalk colour from texNormal[0] at (2,2)
def texcol(i, x, y):
    b = blobs[i]
    W, H, f = struct.unpack_from('<III', b, 4)
    pal = np.frombuffer(b, np.uint8, 1024, 16).reshape(256, 4)
    idx = np.frombuffer(b, np.uint8, W * H, 16 + 1024).reshape(H, W)
    return pal[idx[y, x]]
gc = [texcol(g[k][0], 1, 1) for k in ['texNormal', 'texDessert', 'texGrass']]
w('static const unsigned char BIOME_GROUND[3][4] = {%s};' % ','.join('{%d,%d,%d,255}' % tuple(c[:3]) for c in gc))
print('ground colours', gc)

# tiles: we only need the road shapes; conn index: 0=-Z 1=+X 2=+Z 3=-X
tiles = []
for nm, t in meta['tiles'].items():
    if nm.startswith('brug') or nm == 'roadEmpty' or nm == 'roadRechtdoor':
        continue
    c = t['conn']
    mask = (c[0] << 0) | (c[1] << 1) | (c[2] << 2) | (c[3] << 3)
    tiles.append((mask, M['tile_' + nm]['idx'], nm))
tiles.sort()
w('// road tile models by connection mask (bit0=-Z bit1=+X bit2=+Z bit3=-X)')
w('static const short ROADTILE_BY_MASK[16] = {%s};' % ','.join(str(next((t[1] for t in tiles if t[0] == m), -1)) for m in range(16)))
print('tiles', tiles)

# buildings
def footprint(nm):
    lo, hi = M[nm]['lo'], M[nm]['hi']
    # snap to 6.4 grid; origin cell spans [-3.2,3.2]
    x0 = int(math.floor((lo[0] + 3.2 + 1.5) / 6.4)); x1 = int(math.ceil((hi[0] + 3.2 - 1.5) / 6.4)) - 1
    z0 = int(math.floor((lo[2] + 3.2 + 1.5) / 6.4)); z1 = int(math.ceil((hi[2] + 3.2 - 1.5) / 6.4)) - 1
    return x0, z0, max(x0, x1), max(z0, z1)

bnames = []
for k, lst in meta['buildings'].items():
    for nm in lst:
        if nm not in bnames: bnames.append(nm)
w('typedef struct { short model; signed char x0, z0, x1, z1; unsigned char soft; float height; short col0, ncol; } BuildingDef;')
cols = []
rows = []
for nm in bnames:
    m = M[nm]
    soft = 1 if 'bushTrigger' in m['flags'] else 0
    c0 = len(cols)
    for c in m['cols']:
        if c[6]: continue
        if c[4] - c[1] < 0.6 or c[4] < 0.4: continue
        cols.append(c[:6])
    x0, z0, x1, z1 = footprint(nm)
    rows.append('{%d,%d,%d,%d,%d,%d,%.3ff,%d,%d}' % (m['idx'], x0, z0, x1, z1, soft, m['hi'][1], c0, len(cols) - c0))
w('#define NUM_BUILDINGS %d' % len(bnames))
w('static const BuildingDef BUILDINGS[] = {%s};' % ',\n'.join(rows))
w('static const float BCOLS[][6] = {%s};' % ','.join('{%s}' % ','.join('%.3ff' % v for v in c) for c in cols) if cols else 'static const float BCOLS[1][6];')
for k, lst in meta['buildings'].items():
    w('static const short BL_%s[] = {%s};' % (k, ','.join(str(bnames.index(x)) for x in lst)))
    w('#define NBL_%s %d' % (k, len(lst)))

# vehicles
def mdl(nm):
    m = M[nm]; return m['idx'], m['lo'], m['hi']
w('typedef struct { short model; float lo[3], hi[3]; } VehDef;')
def vrow(nm):
    i, lo, hi = mdl(nm)
    return '{%d,{%.3ff,%.3ff,%.3ff},{%.3ff,%.3ff,%.3ff}}' % (i, *lo, *hi)
w('#define NUM_PLAYERCARS %d' % len(meta['cars']))
w('static const VehDef PLAYERCARS[] = {%s};' % ','.join(vrow(c['variants'][0]) for c in meta['cars']))
w('#define NUM_TRAFFIC %d' % len(meta['traffic']))
w('static const VehDef TRAFFICCARS[] = {%s};' % ','.join(vrow(t) for t in meta['traffic']))
for k, v in meta['police'].items():
    w('static const VehDef COP_%s = %s;' % (k, vrow(v)))
w('static const VehDef COIN_DEF = %s;' % vrow('coin'))
if 'bullet' in M:
    w('static const VehDef BULLET_DEF = %s;' % vrow('bullet'))
open(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '..', 'src', 'gamedata.h'), 'w').write('\n'.join(out) + '\n')
print('ok', len(bnames), 'buildings', len(cols), 'colliders')
